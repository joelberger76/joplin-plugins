// Generates src/altCheckboxes.css (viewer stylesheet) and src/taskIcons.json
// (icon data for the editor script) from src/taskTypes.json and the Lucide
// icon set (lucide-static, ISC licence). Run with: npm run icons
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const taskTypes = require(path.join(root, 'src', 'taskTypes.json'));
const iconDir = path.join(root, 'node_modules', 'lucide-static', 'icons');

// "incomplete" has no Lucide equivalent: a box with its left half filled.
const HALF_BOX = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" stroke-linejoin="round"><rect x="3" y="3" width="18" height="18" rx="3"/><path d="M12 3H6a3 3 0 0 0-3 3v12a3 3 0 0 0 3 3h6z" fill="black"/></svg>';

function loadIcon(name) {
	if (!name) return HALF_BOX;
	return fs.readFileSync(path.join(iconDir, `${name}.svg`), 'utf8')
		.replace(/<!--[\s\S]*?-->/g, '')
		// Drop class/width/height from the root <svg> tag only: child <rect>s need theirs.
		.replace(/<svg[^>]*>/, tag => tag.replace(/\s+(class|width|height)="[^"]*"/g, ''))
		.replace(/currentColor/g, 'black')
		.replace(/\s+/g, ' ')
		.replace(/> </g, '><')
		.trim();
}

function dataUri(svg) {
	return `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/'/g, '%27')}")`;
}

function attrValue(char) {
	return char.replace(/["\\]/g, '\\$&');
}

let css = `/* Generated by tools/build-css.js. Edit src/taskTypes.json and run "npm run icons". */
/* Icons: Lucide (https://lucide.dev), ISC licence. */

li.alt-checkbox {
	list-style: none;
	position: relative;
}

/* The "ul li...[data-task]" selector outranks Joplin's own
   "ul.joplin-checklist li::before" rule, which otherwise draws a second box
   when alternate and standard checkboxes share a list. */
ul li.alt-checkbox[data-task]::before {
	content: "";
	position: absolute;
	left: -1.5em;
	top: 0.2em;
	width: 1.15em;
	height: 1.15em;
	margin-left: 0;
	background-color: var(--alt-checkbox-color, currentColor);
	-webkit-mask: var(--alt-checkbox-icon) center / contain no-repeat;
	mask: var(--alt-checkbox-icon) center / contain no-repeat;
}

li.alt-checkbox[data-task="-"] {
	text-decoration: line-through;
	opacity: 0.6;
}
`;

const editorIcons = {};

for (const [char, def] of Object.entries(taskTypes)) {
	editorIcons[char] = { label: def.label, color: def.color, icon: dataUri(loadIcon(def.icon)) };
	css += `
/* [${char}] ${def.label} */
li.alt-checkbox[data-task="${attrValue(char)}"] {
	--alt-checkbox-color: ${def.color};
	--alt-checkbox-icon: ${dataUri(loadIcon(def.icon))};
}
`;
}

fs.writeFileSync(path.join(root, 'src', 'altCheckboxes.css'), css);
fs.writeFileSync(path.join(root, 'src', 'taskIcons.json'), `${JSON.stringify(editorIcons, null, '\t')}\n`);
console.log(`Wrote src/altCheckboxes.css and src/taskIcons.json with ${Object.keys(taskTypes).length} task types`);
